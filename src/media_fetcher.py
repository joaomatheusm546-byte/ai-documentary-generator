import os
import re
import logging
import requests
from pathlib import Path
from typing import List, Optional, Dict, Any
from urllib.parse import quote_plus
from PIL import Image
from src.config import PEXELS_API_KEY, PIXABAY_API_KEY, TEMP_DIR

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("MediaFetcher")

HEADERS = {
    "User-Agent": "HistoricalDocumentaryBot/1.0 (contact: documentary-engine@openarchive.org)"
}

def clean_query(query: str) -> str:
    # Remove special punctuation that confuses mediawiki search
    return re.sub(r'["\':;,]', '', query).strip()

def search_wikimedia_commons(query: str, min_width: int = 1200) -> Optional[Dict[str, Any]]:
    """
    Searches Wikimedia Commons for high-resolution public domain images matching query.
    """
    clean_q = clean_query(query)
    url = "https://commons.wikimedia.org/w/api.php"
    params = {
        "action": "query",
        "generator": "search",
        "gsrsearch": clean_q,
        "gsrnamespace": 6, # namespace 6 is File:
        "gsrlimit": 8,
        "prop": "imageinfo",
        "iiprop": "url|size|mime",
        "format": "json"
    }
    
    try:
        res = requests.get(url, params=params, headers=HEADERS, timeout=15)
        if res.status_code != 200:
            return None
            
        data = res.json()
        pages = data.get("query", {}).get("pages", {})
        
        candidates = []
        for pid, page in pages.items():
            infos = page.get("imageinfo", [])
            if not infos:
                continue
            info = infos[0]
            mime = info.get("mime", "")
            width = info.get("width", 0)
            height = info.get("height", 0)
            img_url = info.get("url")
            
            # Filter acceptable formats and sizes
            if mime in ["image/jpeg", "image/png", "image/webp"] and width >= min_width:
                # Calculate resolution score
                score = width * height
                # Disfavor icons or pure vertical ribbons
                aspect = width / max(1, height)
                if 0.5 <= aspect <= 2.5:
                    candidates.append({
                        "url": img_url,
                        "width": width,
                        "height": height,
                        "title": page.get("title", ""),
                        "score": score
                    })

        if candidates:
            # Sort by highest resolution
            candidates.sort(key=lambda x: x["score"], reverse=True)
            return candidates[0]
            
    except Exception as e:
        logger.warning(f"Wikimedia search failed for '{query}': {e}")
        
    return None

def search_pexels_photo(query: str) -> Optional[Dict[str, Any]]:
    """
    Searches Pexels photo API if API key is configured.
    """
    if not PEXELS_API_KEY:
        return None
    url = f"https://api.pexels.com/v1/search?query={quote_plus(query)}&per_page=5&orientation=landscape"
    try:
        res = requests.get(url, headers={"Authorization": PEXELS_API_KEY}, timeout=10)
        if res.status_code == 200:
            photos = res.json().get("photos", [])
            if photos:
                best = photos[0]
                return {
                    "url": best["src"]["original"],
                    "width": best["width"],
                    "height": best["height"],
                    "title": best.get("alt", query)
                }
    except Exception as e:
        logger.warning(f"Pexels search failed: {e}")
    return None

def download_file(url: str, dest_path: Path) -> bool:
    """
    Downloads media file to local disk and validates it.
    """
    try:
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        r = requests.get(url, headers=HEADERS, stream=True, timeout=25)
        if r.status_code == 200:
            with open(dest_path, "wb") as f:
                for chunk in r.iter_content(chunk_size=65536):
                    f.write(chunk)
            
            # Verify valid image using Pillow
            with Image.open(dest_path) as img:
                img.verify()
            return True
    except Exception as e:
        logger.warning(f"Failed to download image from {url}: {e}")
        if dest_path.exists():
            dest_path.unlink()
    return False

def fetch_media_for_scene(scene_id: int, search_queries: List[str], topic_fallback: str = "") -> Path:
    """
    Iterates through the scene's search queries to find and download the most relevant archival media.
    Uses multi-stage query relaxation so high-resolution historical assets are consistently found.
    """
    target_file = TEMP_DIR / f"scene_{scene_id:03d}_visual.jpg"
    
    # Stage 1: Exact search queries generated by the director
    for q in search_queries:
        logger.info(f"[Scene {scene_id}] Searching archives for: '{q}'...")
        media = search_pexels_photo(q)
        if not media:
            media = search_wikimedia_commons(q)
        if media:
            logger.info(f"[Scene {scene_id}] Found archival media: {media.get('title')} ({media.get('width')}x{media.get('height')})")
            if download_file(media["url"], target_file):
                return target_file

    # Stage 2: Relaxed queries (strip overly specific descriptors like '19th century', 'engraving', etc.)
    for q in search_queries:
        simplified = re.sub(r'\b(vintage|antique|engraving|illustration|painting|photo|drawing|archives|diagram)\b', '', q, flags=re.IGNORECASE).strip()
        if simplified and simplified != q:
            logger.info(f"[Scene {scene_id}] Searching relaxed query: '{simplified}'...")
            media = search_wikimedia_commons(simplified, min_width=1000)
            if media and download_file(media["url"], target_file):
                return target_file

    # Stage 3: Broad topic fallback
    if topic_fallback:
        logger.info(f"[Scene {scene_id}] Searching topic fallback: '{topic_fallback}'...")
        media = search_wikimedia_commons(topic_fallback, min_width=800)
        if media and download_file(media["url"], target_file):
            return target_file

    # Stage 4: Procedural parchment canvas fallback
    logger.warning(f"[Scene {scene_id}] No archive image found. Generating cinematic archival canvas...")
    create_placeholder_canvas(target_file, f"Archival Scene {scene_id}")
    return target_file

def create_placeholder_canvas(dest_path: Path, caption: str):
    """
    Generates a dark cinematic textured 1920x1080 canvas if no image could be downloaded.
    """
    from PIL import ImageDraw
    img = Image.new("RGB", (1920, 1080), color=(18, 16, 14))
    draw = ImageDraw.Draw(img)
    # Subtle frame
    draw.rectangle([40, 40, 1880, 1040], outline=(60, 50, 40), width=3)
    img.save(dest_path, "JPEG", quality=90)
